// deepMerge: recursively merge `extra` into `base` (extra wins on leaves).
function deepMerge(base: any, extra: any) {
  const out = Array.isArray(base) ? [...base] : { ...base }
  for (const k of Object.keys(extra)) {
    const bv = out[k]
    const ev = extra[k]
    out[k] =
      bv && ev && typeof bv === 'object' && typeof ev === 'object' && !Array.isArray(bv) && !Array.isArray(ev)
        ? deepMerge(bv, ev)
        : ev
  }
  return out
}

export default deepMerge(en, enExtra) as typeof en & typeof enExtra
